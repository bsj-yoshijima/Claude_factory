// この数字を 1 つ上げてコミットする（列の追加・テーブルの追加・制約の変更など）。
//
// 上げると何が起きるか:
//   - オーナーが `npm run db:migrate` を実行するまで、この数字を持つコードは起動しない
//   - まだ pull していない古いコードは、警告だけ出して従来どおり動く
//
// 逆に、コードが無くても困らない変更（コメント修正・インデックスの微調整など）では
// 上げなくてよい。上げるほどメンバーの起動が止まる回数が増える。
